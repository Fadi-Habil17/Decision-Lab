import { ApiProperty } from '@nestjs/swagger';

export class TemplateCriterionResponseDto {
  @ApiProperty({
    type: 'integer',
    description: 'Numeric criterion ID within this template.',
    example: 1,
  })
  id!: number;

  @ApiProperty({ type: String, example: 'Performance' })
  name!: string;

  @ApiProperty({ type: 'integer', minimum: 1, maximum: 100, example: 30 })
  weight!: number;
}

export class TemplateResponseDto {
  @ApiProperty({
    type: 'integer',
    description: 'Numeric application ID generated by the shared counter.',
    example: 1,
  })
  id!: number;

  @ApiProperty({ type: String, example: 'Laptop Purchase' })
  name!: string;

  @ApiProperty({ type: String, example: 'Compare laptops for the bootcamp.' })
  description!: string;

  @ApiProperty({
    type: [TemplateCriterionResponseDto],
    minItems: 2,
    maxItems: 8,
  })
  criteria!: TemplateCriterionResponseDto[];
}
